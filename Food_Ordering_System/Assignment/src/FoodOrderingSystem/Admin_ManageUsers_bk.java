    private int getTabIndexOfTable(JTable table) {
	for (int i = 0; i < tabViewUserInfo.getTabCount(); i++) {
	    Component tabComponent = tabViewUserInfo.getComponentAt(i);

	    if (tabComponent instanceof JScrollPane) {
		JScrollPane scrollPane = (JScrollPane) tabComponent;
		Component viewportComponent = scrollPane.getViewport().getView();

		if (viewportComponent == table) {
		    return i; // Found the tab index containing this table
		}
	    }
	}
	return -1; // Table not found in any tab
    }

