    private void refreshTable(JTable table, String txtFileName, String role) {
	System.out.println("Refreshing table: " + table + " for role: " + role);

	try {
	    DefaultTableModel model = (DefaultTableModel) table.getModel();
	    model.setRowCount(0); // Reset the table

	    FileReader fr = new FileReader(txtFileName);
	    BufferedReader br = new BufferedReader(fr);
	    String read;

	    while ((read = br.readLine()) != null) {
		String[] data = read.split(";"); // Assuming data is separated by semicolons

		Object[] rowData = null;

		switch (role.toLowerCase()) {
		    case "vendor":
			if (data.length >= 11) { // Ensure enough columns exist
			    rowData = new Object[]{
				data[0], // VendorID
				data[1], // First Name
				data[2], // Last Name
				data[3], // DOB
				data[4], // Company Name
				data[5], // Business Registration No.
				data[6], // License Expiry
				data[7], // Contact No.
				data[8], // Address
				data[9], // Email
				data[10] // Vendor Wallet (Deposit for Refund + Revenue Tracking)
			    };
			}
			break;

		    case "customer":
			if (data.length == 6) {
			    rowData = new Object[]{
				data[0], // CustomerID
				data[1], // First Name
				data[2], // Last Name
				data[3], // DOB
				data[4], // Contact No.
				data[5], // Address
				data[6], // Email
				data[7] // Total Credit Amount
			    };
			}
			break;

		    case "runner":
			if (data.length >= 7) {
			    rowData = new Object[]{
				data[0], // RunnerID
				data[1], // First Name
				data[2], // Last Name
				data[3], // DOB
				data[4], // Employee No.
				data[5], // Identification No.
				data[6], // Contact No.
				data[7], // Address
				data[8] // Email
			    };
			}
			break;

		    default:
			System.out.println("Invalid role: " + role);
			break;
		}

		if (rowData != null) {
		    model.addRow(rowData);
		}
	    }

	    br.close(); // Close file reader
	    //System.out.println("Data Import Complete!");

	} catch (Exception e) {
	    JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
	}
    }

