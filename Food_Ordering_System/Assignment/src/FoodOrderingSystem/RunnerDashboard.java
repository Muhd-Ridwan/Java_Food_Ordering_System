    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased
	// TODO add your handling code here:
	try {
	    String searchText = txtSearch.getText().trim(); // Get search text
	    DefaultTableModel model = (DefaultTableModel) feedbackTable.getModel();
	    model.setRowCount(0); // Clear the table before adding data

	    if (searchText.isEmpty()) {
		// If search text is empty, reset the table to show all data
		refreshData(false);
	    }

	    FileReader fr = new FileReader("Runner Review.txt");
	    BufferedReader br = new BufferedReader(fr);
	    String line;

	    // Read through the file line by line
	    while ((line = br.readLine()) != null) {

		String feedbackID = line.split(";")[0].trim();
		String orderID = line.split(";")[1].trim();
		String runnerID = line.split(";")[2].trim();
		String ratings = line.split(";")[3].trim();
		String comment = line.split(";")[4].trim();

		// Check if any field matches the search text
		if (feedbackID.equalsIgnoreCase(searchText)
			|| orderID.equalsIgnoreCase(searchText)
			|| runnerID.equalsIgnoreCase(searchText)
			|| ratings.equalsIgnoreCase(searchText)
			|| comment.equalsIgnoreCase(searchText)) {
		    // Add the matching record to the table
		    model.addRow(new Object[]{feedbackID, orderID, runnerID, ratings, comment});
		}
	    }
	    br.close(); // Close the file reader
	} catch (IOException e) {
	    JOptionPane.showMessageDialog(null, "Error reading file: " + e.getMessage());
	} catch (Exception e) {
	    JOptionPane.showMessageDialog(null, "Unexpected Error: " + e.getMessage());
	}
    }//GEN-LAST:event_txtSearchKeyReleased

