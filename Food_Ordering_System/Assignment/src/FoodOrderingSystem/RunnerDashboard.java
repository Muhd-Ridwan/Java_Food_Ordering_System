    public void refreshData(boolean isFilterRequired) {
	try {
	    DefaultTableModel model = (DefaultTableModel) feedbackTable.getModel();
	    model.setRowCount(0);//reset table
	    FileReader fr = new FileReader("Runner Review.txt");
	    BufferedReader br = new BufferedReader(fr);
	    String read;

	    ratingSum = 0;
	    ratingRecordCount = 0;
	    while ((read = br.readLine()) != null) {
		if (this.runnerID.equalsIgnoreCase(read.split(";")[2]) || !isFilterRequired) {
		    String feedbackID = read.split(";")[0];
		    String orderID = read.split(";")[1];
		    String runnerID = read.split(";")[2];
		    String ratings = read.split(";")[3];
		    String comment = read.split(";")[4];

		    model.addRow(
			    new Object[]{
				feedbackID,
				orderID,
				runnerID,
				ratings,
				comment
			    }
		    );

		    // get ratings and feedbackCount
		    ratingSum = ratingSum + Double.parseDouble(ratings);
		    ratingRecordCount++;
		}
	    }

	} catch (Exception e) {
	    JOptionPane.showMessageDialog(null, e.getMessage());
	}
    }
