    private void updateCustomerCreditAmount(double updatedCreditAmount) {
	File file = new File("Customer Profile.txt");
	List<String[]> allData = new ArrayList<>();

	try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
	    String line;

	    // Read all lines into an ArrayList
	    while ((line = reader.readLine()) != null) {
		String[] data = line.split(";");

		// Update credit amount if customer ID matches
		if (data.length > 7 && data[0].equals(this.customerID)) {
		    data[7] = String.valueOf(updatedCreditAmount);
		}

		allData.add(data); // Store modified or unchanged data
	    }
	} catch (IOException e) {
	    JOptionPane.showMessageDialog(this, "Error reading customer profile: " + e.getMessage());
	    return;
	}

	// Write updated data back to the file
	try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
	    for (String[] data : allData) {
		writer.write(String.join(";", data));
		writer.newLine();
	    }
	} catch (IOException e) {
	    JOptionPane.showMessageDialog(this, "Error writing updated credit amount: " + e.getMessage());
	}
    }

    public void writeToTxFile(String customerID, double transactionAmount, String transactionType) {
	File file = new File("Transaction.txt");
	List<String> allData = new ArrayList<>();

	// Generate new Transaction ID (Assuming it increments)
	String newTransactionID = txtTxID.getText();

	// Get current date and time
	LocalDateTime now = LocalDateTime.now();
	DateTimeFormatter dateFormatter = DateTimeFormatter.ofPattern("dd-MM-yyyy");
	DateTimeFormatter timeFormatter = DateTimeFormatter.ofPattern("hh:mm:ss a");

	String currentDate = now.format(dateFormatter);
	String currentTime = now.format(timeFormatter);

	try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
	    String line;

	    // Read all lines into an ArrayList
	    while ((line = reader.readLine()) != null) {
		allData.add(line); // Store existing transaction records
	    }
	} catch (IOException e) {
	    JOptionPane.showMessageDialog(null, "Error reading transaction file: " + e.getMessage());
	    return;
	}

	// Format new transaction record
	String newTransactionRecord = newTransactionID + ";" + customerID + ";" + currentDate + ";"
		+ currentTime + ";" + String.format("%.2f", transactionAmount) + ";" + transactionType;

	// Add new transaction record to list
	allData.add(newTransactionRecord);

	// Write all data back to the file
	try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
	    for (String record : allData) {
		writer.write(record);
		writer.newLine();
	    }
	} catch (IOException e) {
	    JOptionPane.showMessageDialog(null, "Error writing transaction file: " + e.getMessage());
	}
    }

