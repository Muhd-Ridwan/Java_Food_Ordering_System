    public void populateFormFromTableSelection() {
	int selectedRow = notificationTable.getSelectedRow();
	if (selectedRow != -1) { // Ensure a row is selected
	    notificationID = (String) notificationTable.getValueAt(selectedRow, 0);
	    customerID = (String) notificationTable.getValueAt(selectedRow, 1);
	    topUpAmount = (String) notificationTable.getValueAt(selectedRow, 4);

	}

	// get current balance 
	Customer cus = new Customer(customerID);
	currBalance = Double.toString(cus.getCurrentBalance());

	txtCustomerID.setText(customerID);
	txtTopUpAmount.setText(topUpAmount);
	lblCurrBalance.setText(currBalance);
	try {
	    FileReader fr = new FileReader("Transaction.txt");
	    BufferedReader br = new BufferedReader(fr);
	    String read;
	    if ((read = br.readLine()) != null) {
		newTxID = IDGenerator.generateTxID("Transaction.txt");
		txtTxID.setText(newTxID);
	    } else {
		newTxID = "-";
		txtTxID.setText(newTxID);
	    }
	} catch (Exception e) {
	    JOptionPane.showMessageDialog(null, e.getMessage());
	}

    }

    public void refreshDataTx() {
	try {
	    DefaultTableModel model = (DefaultTableModel) TxTable.getModel();
	    model.setRowCount(0);//reset table
	    FileReader fr = new FileReader("Transaction.txt");
	    BufferedReader br = new BufferedReader(fr);
	    String read;

	    while ((read = br.readLine()) != null) {

		String TxID = read.split(";")[0];
		String customerID = read.split(";")[1];
		String date = read.split(";")[2];
		String time = read.split(";")[3];
		String amount = read.split(";")[4];
		String txType = read.split(";")[5];

		model.addRow(
			new Object[]{
			    TxID,
			    customerID,
			    date,
			    time,
			    amount,
			    txType
			}
		);
	    }

	} catch (Exception e) {
	    JOptionPane.showMessageDialog(null, e.getMessage());
	}
    }

    public void refreshDataNotification() {
	try {
	    DefaultTableModel model = (DefaultTableModel) notificationTable.getModel();
	    model.setRowCount(0);//reset table
	    FileReader fr = new FileReader("Notification.txt");
	    BufferedReader br = new BufferedReader(fr);
	    String read;

	    while ((read = br.readLine()) != null) {

		if (read.split(";")[2].toLowerCase().contains("request")) {
		    String notificationID = read.split(";")[0];
		    String customerID = read.split(";")[1];
		    String topUpStatus = read.split(";")[2];
		    String date = read.split(";")[3];
		    String amount = read.split(";")[4];

		    model.addRow(
			    new Object[]{
				notificationID,
				customerID,
				topUpStatus,
				date,
				amount
			    }
		    );
		}

	    }

	} catch (Exception e) {
	    JOptionPane.showMessageDialog(null, e.getMessage());
	}
    }

