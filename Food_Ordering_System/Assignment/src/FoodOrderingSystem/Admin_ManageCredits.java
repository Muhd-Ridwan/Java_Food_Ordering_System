    private void btnTopUpCreditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTopUpCreditActionPerformed
	// TODO add your handling code here:
	double newBalance = 0.0;
	if (validateTopUp(txtTxID, txtCustomerID, txtTopUpAmount)) {
	    newBalance = Double.parseDouble(currBalance) + Double.parseDouble(txtTopUpAmount.getText());
	    updateCustomerCreditAmount(Double.parseDouble(String.format("%.2f", newBalance)));
	    writeToTxFile(customerID, Double.parseDouble(String.format("%.2f", newBalance)), "Credit");
	    refreshDataTx();
	    writeToNotificationFile(notificationID);
	    refreshDataNotification();
	    this.newBalance = String.format("%.2f", newBalance);
	}
    }//GEN-LAST:event_btnTopUpCreditActionPerformed

